def elapsed(seconds: int) -> str:
    hours, rest = divmod(int(seconds), 3600)
    minutes, seconds = divmod(rest, 60)
    return f"{hours}:{minutes:02d}:{seconds:02d}" if hours else f"{minutes}:{seconds:02d}"


def ask_lines(title, app) -> tuple[str, str | None]:
    return ASK, f"{title} · {app}" if title and app else app or None


def export_name(meeting) -> str:
    title = re.sub(r'[\\/:*?"<>|]', '-', meeting.title)
    return f"{meeting.started_at[:10]} {title}.md"
